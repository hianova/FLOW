#!/usr/bin/env sh
set -eu

CC_BIN="${CC:-cc}"
UNAME_S="$(uname -s 2>/dev/null || echo Unknown)"
UNAME_M="$(uname -m 2>/dev/null || echo Unknown)"

PAGE_BYTES="${FLOW_HW_PAGE_BYTES:-}"
CACHE_LINE_BYTES="${FLOW_HW_CACHE_LINE_BYTES:-}"
L1D_BYTES="${FLOW_HW_L1D_BYTES:-}"
VECTOR_BYTES="${FLOW_HW_VECTOR_BYTES:-}"
WAVE_LANES="${FLOW_HW_WAVE_LANES:-64}"

if [ "$UNAME_S" = "Darwin" ]; then
    [ -n "$PAGE_BYTES" ]       || PAGE_BYTES="$(sysctl -n hw.pagesize 2>/dev/null || true)"
    [ -n "$CACHE_LINE_BYTES" ] || CACHE_LINE_BYTES="$(sysctl -n hw.cachelinesize 2>/dev/null || true)"
    [ -n "$L1D_BYTES" ]        || L1D_BYTES="$(sysctl -n hw.l1dcachesize 2>/dev/null || true)"
elif [ "$UNAME_S" = "Linux" ]; then
    [ -n "$PAGE_BYTES" ]       || PAGE_BYTES="$(getconf PAGESIZE 2>/dev/null || true)"
    [ -n "$CACHE_LINE_BYTES" ] || CACHE_LINE_BYTES="$(getconf LEVEL1_DCACHE_LINESIZE 2>/dev/null || true)"
    [ -n "$L1D_BYTES" ]        || L1D_BYTES="$(getconf LEVEL1_DCACHE_SIZE 2>/dev/null || true)"
fi

if [ -z "$VECTOR_BYTES" ]; then
    case "$UNAME_M" in
        arm64|aarch64)
            VECTOR_BYTES=16
            ;;
        x86_64|amd64)
            DEFS="$($CC_BIN -march=native -dM -E - </dev/null 2>/dev/null || $CC_BIN -dM -E - </dev/null 2>/dev/null || true)"
            if printf '%s\n' "$DEFS" | grep -q '__AVX512F__'; then
                VECTOR_BYTES=64
            elif printf '%s\n' "$DEFS" | grep -q '__AVX2__'; then
                VECTOR_BYTES=32
            else
                VECTOR_BYTES=16
            fi
            ;;
    esac
fi

for var_name in PAGE_BYTES CACHE_LINE_BYTES L1D_BYTES VECTOR_BYTES WAVE_LANES; do
    eval "val=\$$var_name"
    case "$val" in
        ''|*[!0-9]*|0)
            echo "error: failed to detect FLOW_HW_${var_name} (got '$val'); override via make FLOW_HW_${var_name}=..." >&2
            exit 1
            ;;
    esac
done

cat <<EOF
/* Auto-generated by tools/gen_hw_spec.sh — DO NOT EDIT */
#ifndef FLOW_HW_SPEC_H
#define FLOW_HW_SPEC_H

#define FLOW_HW_PAGE_BYTES        ${PAGE_BYTES}u
#define FLOW_HW_CACHE_LINE_BYTES  ${CACHE_LINE_BYTES}u
#define FLOW_HW_L1D_BYTES         ${L1D_BYTES}u
#define FLOW_HW_VECTOR_BYTES      ${VECTOR_BYTES}u
#define FLOW_HW_WAVE_LANES        ${WAVE_LANES}u

#endif /* FLOW_HW_SPEC_H */
EOF
