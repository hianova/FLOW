int flow_emit_builtin_component(FILE *output, const SemanticIR *ir, const Component *c, const SearchResult *s, const VerificationReport *v, int reload_adapter) {
    size_t cap = s ? (size_t)s->capacity : (size_t)ir->input_max_count, shd = s ? (size_t)s->shards : 1;
    if (cap < 1) cap = 1;
    if (shd < 1) shd = 1;
    if (reload_adapter) { emit_reload_adapter(output, c, cap, shd); return ferror(output) == 0; }
    flow_emit_metadata(output, ir, c, s, v);
    flow_emit_abi_exports(output, ir, c, cap);
    if (!ir || !ir->omit_dummy_main) {
        fputs("#ifndef FLOW_SHARED_LIB\nint main(void) { return 0; }\n#endif\n", output);
    }
    return ferror(output) == 0;
}
int emit_c(FILE *output, const SemanticIR *ir, const Component *c, const SearchResult *s, const VerificationReport *v, int reload_adapter) {
    if (!output || !ir || !c || !v) return 0;
    emit_candidate_plan(output, ir);
    return flow_component_emit(output, ir, c, s, v, reload_adapter);
}
int flow_backend_run_in_memory(const SemanticIR *ir, const Component *c, const SearchResult *s, const VerificationReport *v, FILE *out) {
    if (!ir || !c) return 0;
    if (!out) out = stdout;
    size_t cap = s ? (size_t)s->capacity : (size_t)ir->input_max_count, thr = s ? (size_t)s->threads : 1, shd = s ? (size_t)s->shards : 1;
    if (cap < 1) cap = 1;
    if (thr < 1) thr = 1;
    if (shd < 1) shd = 1;
    (void)v;
    fprintf(out, "FLOW Lean 4 module: %s | component: %s | capacity: %zu | structs: %zu | enums: %zu | functions: %zu | theorems: %zu\n",
            ir->flow_name[0] ? ir->flow_name : "lean_module", c->id, cap, ir->lean_struct_count, ir->lean_enum_count, ir->lean_function_count, ir->lean_theorem_count);
    return 1;
}
