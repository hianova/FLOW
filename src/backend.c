static void flow_emit_metadata(FILE *output, const SemanticIR *ir, const Component *c, const SearchResult *s, const VerificationReport *v) {
    const FlowPlugin *p = flow_component_plugin(c); const FlowTuning t = s ? s->tuning : flow_default_tuning(ir, c);
    fprintf(output, "/* Generated by FLOW Lean 4 -> C17 Synthesizer: %s */\n", ir->flow_name[0] ? ir->flow_name : c->id);
    if (ir->project_name[0]) fprintf(output, "/* Project: %s */\n", ir->project_name);
    fprintf(output,
        "/* Semantic IR: structs=%zu enums=%zu functions=%zu theorems=%zu stride=%zu align=%zu deterministic=%d lean_certified=%d */\n"
        "/* Selected component: %s (%s) plugin=%s */\n"
        "/* Tuning: workload_bytes=%zu buffer_bytes=%zu initial_capacity=%zu growth_percent=%u batch_size=%zu arena_bytes=%zu */\n"
        "/* Verification: status=%s capacity=%zu estimated_bytes=%zu message=%s */\n",
        ir->lean_struct_count, ir->lean_enum_count, ir->lean_function_count, ir->lean_theorem_count,
        ir->input_stride_bytes, ir->input_align_bytes, ir->fact_deterministic, ir->fact_lean_certified,
        c->id, c->kind, p ? p->name : "",
        ir->workload_bytes, t.buffer_bytes, t.initial_capacity, t.growth_percent, t.batch_size, t.arena_bytes,
        verification_status_name(v->status), v->capacity, v->estimated_bytes, v->message);
    if (s) {
        fprintf(output, "/* C search: mode=%s iterations=%zu seed=%u genome=%llu energy=%.6f benchmark_ns=%llu capacity=%.0f threads=%.0f shards=%.0f */\n",
                s->measured ? "benchmark" : "model", s->iterations, s->seed, (unsigned long long)s->genome,
                s->energy, (unsigned long long)s->benchmark_ns, s->capacity, s->threads, s->shards);
    }
}
static void emit_candidate_plan(FILE *output, const SemanticIR *ir) {
    size_t count = compatible_component_count(ir);
    fprintf(output,
        "\n#include <stddef.h>\ntypedef struct { const char *name, *kind, *resource, *capability, *domain_contract, *flow_binding, *domain, *fallback_policy; int latency_score, memory_score, supports_parallelizable; size_t memory_fixed_bytes, memory_bytes_per_capacity; const char *plugin; } FlowGeneratedCandidatePlan;\n"
        "#define FLOW_GENERATED_CANDIDATE_COUNT %zu\nstatic const FlowGeneratedCandidatePlan FLOW_GENERATED_CANDIDATES[%zu] = {\n", count, count == 0 ? 1u : count);
    for (size_t i = 0; i < count; ++i) {
        const Component *cand = compatible_component_at(ir, i); const FlowPlugin *p = flow_component_plugin(cand);
        fprintf(output, "    {\"%s\", \"%s\", \"%s\", \"%s\", \"%s\", \"%s\", \"%s\", \"%s\", %d, %d, %d, %zu, %zu, \"%s\"}%s\n",
                cand->id, cand->kind, cand->resource ? cand->resource : "", cand->capability ? cand->capability : "",
                cand->domain_contract ? cand->domain_contract : "", cand->flow_binding ? cand->flow_binding : "",
                ir->domain_name, ir->fallback_policy, cand->latency_score, cand->memory_score,
                cand->supports_parallelizable, cand->memory_fixed_bytes, cand->memory_bytes_per_capacity, p ? p->name : "", i + 1 == count ? "" : ",");
    }
    fprintf(output,
        "};\nconst FlowGeneratedCandidatePlan *flow_generated_candidate_plans(size_t *count_out);\n"
        "const FlowGeneratedCandidatePlan *flow_generated_candidate_plans(size_t *count_out) { if (count_out) *count_out = FLOW_GENERATED_CANDIDATE_COUNT; return FLOW_GENERATED_CANDIDATES; }\n\n");
}
static void emit_reload_adapter(FILE *output, const Component *c, size_t cap, size_t shards) {
    const int is_hash = strcmp(c->id, "sharded_hash") == 0; fprintf(output,
        "/* Generated by FLOW: static reload adapter for %s. */\n#include \"reload.h\"\n#include <pthread.h>\n#include <stdatomic.h>\n#include <stdint.h>\n#include <stdlib.h>\n"
        "#define FLOW_RELOAD_CAPACITY %zu\n#define FLOW_RELOAD_SHARDS %zu\n#define FLOW_RELOAD_SLOTS_PER_SHARD ((FLOW_RELOAD_CAPACITY + FLOW_RELOAD_SHARDS - 1) / FLOW_RELOAD_SHARDS)\n"
        "typedef struct { int id; _Atomic int occupied; _Atomic int score; } flow_reload_entry;\n%s"
        "static const FlowSchemaField FLOW_RELOAD_FIELDS[] = { {\"entries\", \"entry[]\", FLOW_SCHEMA_FIELD_PERSISTENT}, {\"capacity\", \"u32\", FLOW_SCHEMA_FIELD_DEFAULTABLE | FLOW_SCHEMA_FIELD_PERSISTENT} };\n"
        "static const FlowSchema FLOW_RELOAD_SCHEMA = {\"generated_collection\", 1, FLOW_RELOAD_FIELDS, 2};\n"
        "static int flow_reload_mutation(const FlowMutation *m, int *id, int *score) {\n"
        "    if (!m || !m->key || m->key_size != sizeof(*id)) return 0;\n    *id = *(const int *)m->key;\n"
        "    if (m->kind == FLOW_MUTATION_DELETE) return m->value == NULL && m->value_size == 0;\n"
        "    if (m->kind != FLOW_MUTATION_UPSERT || !m->value || m->value_size != sizeof(*score)) return 0;\n"
        "    *score = *(const int *)m->value; return 1;\n}\n", c->id, cap < 1 ? 1 : cap, shards < 1 ? 1 : shards,
        is_hash ? "typedef struct { flow_reload_entry slots[FLOW_RELOAD_SHARDS][FLOW_RELOAD_SLOTS_PER_SHARD]; pthread_mutex_t locks[FLOW_RELOAD_SHARDS]; } flow_reload_state;\n"
                : "typedef struct { flow_reload_entry entries[FLOW_RELOAD_CAPACITY]; pthread_mutex_t lock; } flow_reload_state;\n");
    if (is_hash) {
        fputs("static size_t flow_reload_hash(int id) { return (size_t)((uint32_t)id * UINT32_C(2654435761)); }\n"
              "static flow_reload_entry *flow_reload_find(flow_reload_state *s, int id, int empty) { const size_t sh = flow_reload_hash(id) % FLOW_RELOAD_SHARDS; flow_reload_entry *fe = NULL; for (size_t sl = 0; sl < FLOW_RELOAD_SLOTS_PER_SHARD; ++sl) { flow_reload_entry *e = &s->slots[sh][sl]; if (atomic_load_explicit(&e->occupied, memory_order_acquire)) { if (e->id == id) return e; } else if (!fe) fe = e; } return empty ? fe : NULL; }\n"
              "static pthread_mutex_t *flow_reload_lock(flow_reload_state *s, int id) { return &s->locks[flow_reload_hash(id) % FLOW_RELOAD_SHARDS]; }\n"
              "static int flow_reload_init(void *hc, void **so) { (void)hc; flow_reload_state *s = calloc(1, sizeof(*s)); if (!s) return -1; for (size_t sh = 0; sh < FLOW_RELOAD_SHARDS; ++sh) if (pthread_mutex_init(&s->locks[sh], NULL) != 0) return -1; *so = s; return 0; }\n"
              "static void flow_reload_drop(void *hc, void *rs) { (void)hc; flow_reload_state *s = rs; for (size_t sh = 0; sh < FLOW_RELOAD_SHARDS; ++sh) pthread_mutex_destroy(&s->locks[sh]); free(s); }\n", output);
    } else {
        fputs("static flow_reload_entry *flow_reload_find(flow_reload_state *s, int id, int empty) { flow_reload_entry *fe = NULL; for (size_t i = 0; i < FLOW_RELOAD_CAPACITY; ++i) { flow_reload_entry *e = &s->entries[i]; if (atomic_load_explicit(&e->occupied, memory_order_acquire)) { if (e->id == id) return e; } else if (!fe) fe = e; } return empty ? fe : NULL; }\n"
              "static pthread_mutex_t *flow_reload_lock(flow_reload_state *s, int id) { (void)id; return &s->lock; }\n"
              "static int flow_reload_init(void *hc, void **so) { (void)hc; flow_reload_state *s = calloc(1, sizeof(*s)); if (!s || pthread_mutex_init(&s->lock, NULL) != 0) { free(s); return -1; } *so = s; return 0; }\n"
              "static void flow_reload_drop(void *hc, void *rs) { (void)hc; flow_reload_state *s = rs; pthread_mutex_destroy(&s->lock); free(s); }\n", output);
    }
    fprintf(output,
        "static int flow_reload_run(void *hc, void *rs, const void *in, void *out) { (void)hc; flow_reload_state *s = rs; const int id = *(const int *)in; pthread_mutex_t *lk = flow_reload_lock(s, id); pthread_mutex_lock(lk); flow_reload_entry *e = flow_reload_find(s, id, 0); if (!e) { pthread_mutex_unlock(lk); return -1; } *(int *)out = atomic_load_explicit(&e->score, memory_order_acquire); pthread_mutex_unlock(lk); return 0; }\n"
        "static int flow_reload_apply_unit(void *hc, void *rs, const FlowMutation *m) { (void)hc; flow_reload_state *s = rs; int id, score = 0; if (!flow_reload_mutation(m, &id, &score)) return -1; pthread_mutex_t *lk = flow_reload_lock(s, id); pthread_mutex_lock(lk); flow_reload_entry *e = flow_reload_find(s, id, m->kind == FLOW_MUTATION_UPSERT); if (!e) { pthread_mutex_unlock(lk); return -1; } if (m->kind == FLOW_MUTATION_DELETE) atomic_store_explicit(&e->occupied, 0, memory_order_release); else { e->id = id; atomic_store_explicit(&e->score, score, memory_order_release); atomic_store_explicit(&e->occupied, 1, memory_order_release); } pthread_mutex_unlock(lk); return 0; }\n"
        "static FlowUnit FLOW_RELOAD_UNIT = { .abi_version = FLOW_RELOAD_ABI_VERSION, .constraint_hash = UINT64_C(0xF001), .capability_hash = UINT64_C(0xF002), .name = \"%s\", .init = flow_reload_init, .run = flow_reload_run, .apply = flow_reload_apply_unit, .drop = flow_reload_drop, .schema = &FLOW_RELOAD_SCHEMA };\n"
        "const FlowUnit *flow_generated_unit(void) { FLOW_RELOAD_UNIT.semantic_schema_hash = flow_schema_hash(&FLOW_RELOAD_SCHEMA); return &FLOW_RELOAD_UNIT; }\n", c->id);
}
static const char *lean_scalar_to_c_type(const char *t) {
    if (!t) return "uint64_t";
    if (!strcmp(t, "Bool")) return "bool";
    if (!strcmp(t, "Float") || !strcmp(t, "\xe2\x84\x9d") || !strcmp(t, "Real")) return "double";
    if (!strcmp(t, "Float32")) return "float";
    if (!strcmp(t, "UInt32")) return "uint32_t";
    if (!strcmp(t, "Int32")) return "int32_t";
    if (!strcmp(t, "UInt16")) return "uint16_t";
    if (!strcmp(t, "Int16")) return "int16_t";
    if (!strcmp(t, "UInt8")) return "uint8_t";
    if (!strcmp(t, "Int8")) return "int8_t";
    if (!strcmp(t, "Int") || !strcmp(t, "Int64")) return "int64_t";
    return "uint64_t";
}
static const FlowLeanStruct *find_ir_lean_struct(const SemanticIR *ir, const char *name) {
    if (!ir || !name || !name[0]) return NULL;
    for (size_t i = 0; i < ir->lean_struct_count; ++i)
        if (strcmp(ir->lean_structs[i].name, name) == 0) return &ir->lean_structs[i];
    return NULL;
}
static const char *lean_type_to_c_type(const SemanticIR *ir, const char *t) {
    if (!t) return "uint64_t";
    if (find_ir_lean_struct(ir, t)) return t;
    if (ir) {
        for (size_t i = 0; i < ir->lean_enum_count; ++i)
            if (strcmp(ir->lean_enums[i].name, t) == 0) return t;
    }
    return lean_scalar_to_c_type(t);
}
static int is_lean_kw_at(const char *p, const char *start, const char *end, const char *kw, size_t kwlen) {
    if ((size_t)(end - p) < kwlen || strncmp(p, kw, kwlen) != 0) return 0;
    int l_ok = (p == start) || isspace((unsigned char)p[-1]) || p[-1] == '(';
    int r_ok = (p + kwlen == end) || isspace((unsigned char)p[kwlen]) || p[kwlen] == '(' || p[kwlen] == ')';
    return l_ok && r_ok;
}
static void subst_lean_var(const char *src, size_t src_len, const char *var, const char *val, size_t val_len, char *out, size_t out_max) {
    size_t vlen = strlen(var), j = 0;
    for (size_t i = 0; i < src_len && j + 4 < out_max; ) {
        if (i + vlen <= src_len && !strncmp(src + i, var, vlen)) {
            int l_ok = (i == 0) || (!isalnum((unsigned char)src[i - 1]) && src[i - 1] != '_');
            int r_ok = (i + vlen == src_len) || (!isalnum((unsigned char)src[i + vlen]) && src[i + vlen] != '_');
            if (l_ok && r_ok && j + val_len + 3 < out_max) {
                out[j++] = '('; memcpy(out + j, val, val_len); j += val_len; out[j++] = ')';
                i += vlen; continue;
            }
        }
        out[j++] = src[i++];
    }
    out[j] = '\0';
}
typedef enum { LEAN_EXPR_NAT = 0, LEAN_EXPR_UINT = 1, LEAN_EXPR_INT = 2, LEAN_EXPR_FLOAT = 3, LEAN_EXPR_FX64 = 4 } LeanExprMode;
static LeanExprMode infer_c_type_expr_mode(const char *c_type, LeanExprMode fallback) {
    if (!c_type) return fallback;
    if (!strcmp(c_type, "double") || !strcmp(c_type, "float")) return LEAN_EXPR_FLOAT;
    if (!strcmp(c_type, "int64_t") || !strcmp(c_type, "int32_t") || !strcmp(c_type, "int16_t") || !strcmp(c_type, "int8_t")) return LEAN_EXPR_INT;
    if (!strcmp(c_type, "uint64_t") || !strcmp(c_type, "uint32_t") || !strcmp(c_type, "uint16_t") || !strcmp(c_type, "uint8_t") || !strcmp(c_type, "bool")) return LEAN_EXPR_UINT;
    return fallback;
}
static LeanExprMode infer_fn_expr_mode(const FlowLeanFunction *fn) {
    if (!fn) return LEAN_EXPR_NAT;
    if (!strcmp(fn->return_type, "Float") || !strcmp(fn->return_type, "Float32")) return LEAN_EXPR_FLOAT;
    for (size_t i = 0; i < fn->param_count; ++i)
        if (!strcmp(fn->param_types[i], "Float") || !strcmp(fn->param_types[i], "Float32")) return LEAN_EXPR_FLOAT;
    if (!strcmp(fn->return_type, "Int") || !strcmp(fn->return_type, "Int64") || !strcmp(fn->return_type, "Int32") ||
        !strcmp(fn->return_type, "Int16") || !strcmp(fn->return_type, "Int8")) return LEAN_EXPR_INT;
    for (size_t i = 0; i < fn->param_count; ++i)
        if (!strcmp(fn->param_types[i], "Int") || !strcmp(fn->param_types[i], "Int64") || !strcmp(fn->param_types[i], "Int32") ||
            !strcmp(fn->param_types[i], "Int16") || !strcmp(fn->param_types[i], "Int8")) return LEAN_EXPR_INT;
    if (!strcmp(fn->return_type, "UInt64") || !strcmp(fn->return_type, "UInt32") || !strcmp(fn->return_type, "UInt16") ||
        !strcmp(fn->return_type, "UInt8")) return LEAN_EXPR_UINT;
    return LEAN_EXPR_NAT;
}
static const FlowLeanFunction *find_ir_lean_fn_len(const SemanticIR *ir, const char *name, size_t len) {
    if (!ir || !name || !len) return NULL;
    for (size_t i = 0; i < ir->lean_function_count; ++i)
        if (strlen(ir->lean_functions[i].name) == len && !strncmp(ir->lean_functions[i].name, name, len))
            return &ir->lean_functions[i];
    return NULL;
}
static void emit_norm_lean_slice(FILE *out, const SemanticIR *ir, const char *s, size_t len, LeanExprMode mode, int is_header_inline) {
    for (;;) {
        while (len > 0 && isspace((unsigned char)*s)) { s++; len--; }
        while (len > 0 && isspace((unsigned char)s[len - 1])) len--;
        if (len >= 2 && s[0] == '(' && s[len - 1] == ')') {
            int d = 0, wrapped = 1;
            for (size_t i = 0; i + 1 < len; ++i) {
                if (s[i] == '(') d++;
                else if (s[i] == ')') { if (--d == 0) { wrapped = 0; break; } }
            }
            if (wrapped) { s++; len -= 2; continue; }
        }
        break;
    }
    if (len == 0) { fputs("0", out); return; }
    const char *end = s + len;
    if (is_lean_kw_at(s, s, end, "let", 3)) {
        const char *ce = NULL; int pd = 0;
        for (const char *p = s + 3; p + 1 < end; ++p) {
            if (*p == '(') pd++; else if (*p == ')' && pd > 0) pd--;
            else if (pd == 0 && p[0] == ':' && p[1] == '=') { ce = p; break; }
        }
        if (ce) {
            char var[FLOW_NAME] = {0}; size_t k = 0;
            for (const char *p = s + 3; p < ce; ++p) {
                if (*p == ':') break;
                if (!isspace((unsigned char)*p) && k + 1 < sizeof(var)) var[k++] = *p;
            }
            const char *rhs = ce + 2;
            while (rhs < end && isspace((unsigned char)*rhs)) ++rhs;
            const char *rhs_end = NULL, *rest = NULL;
            pd = 0; int ld = 0;
            for (const char *p = rhs; p < end; ++p) {
                if (*p == '(') pd++; else if (*p == ')' && pd > 0) pd--;
                else if (pd == 0 && is_lean_kw_at(p, rhs, end, "let", 3)) ld++;
                else if (pd == 0 && is_lean_kw_at(p, rhs, end, "in", 2)) {
                    if (ld == 0) { rhs_end = p; rest = p + 2; break; }
                    ld--;
                }
            }
            if (!rhs_end) {
                pd = 0; int id = 0;
                for (const char *p = rhs; p < end; ++p) {
                    if (*p == '(') pd++; else if (*p == ')' && pd > 0) pd--;
                    else if (pd == 0 && is_lean_kw_at(p, rhs, end, "if", 2)) id++;
                    else if (pd == 0 && is_lean_kw_at(p, rhs, end, "else", 4) && id > 0) id--;
                    else if (pd == 0 && id == 0 && (*p == '\n' || *p == ';')) { rhs_end = p; rest = p + 1; break; }
                }
            }
            if (!rhs_end) { rhs_end = end; rest = end; }
            while (rhs_end > rhs && isspace((unsigned char)rhs_end[-1])) --rhs_end;
            while (rest < end && isspace((unsigned char)*rest)) rest++;
            if (is_lean_kw_at(rest, rest, end, "in", 2)) rest += 2;
            char sub[8192];
            subst_lean_var(rest, (size_t)(end - rest), var, rhs, (size_t)(rhs_end - rhs), sub, sizeof(sub));
            emit_norm_lean_slice(out, ir, sub, strlen(sub), mode, is_header_inline); return;
        }
    }
    if (is_lean_kw_at(s, s, end, "match", 5)) {
        const char *w = NULL; int pd = 0;
        for (const char *p = s + 5; p < end; ++p) {
            if (*p == '(') pd++; else if (*p == ')' && pd > 0) pd--;
            else if (pd == 0 && is_lean_kw_at(p, s, end, "with", 4)) { w = p; break; }
        }
        if (w) {
            const char *scrut = s + 5; size_t scrut_len = (size_t)(w - scrut);
            const char *arms[16]; size_t arm_cnt = 0; pd = 0;
            for (const char *p = w + 4; p < end; ++p) {
                if (*p == '(') pd++; else if (*p == ')' && pd > 0) pd--;
                else if (pd == 0 && *p == '|' && (p == w + 4 || p[-1] != '|') && (p + 1 == end || p[1] != '|')) {
                    if (arm_cnt < 16) arms[arm_cnt++] = p;
                }
            }
            if (arm_cnt > 0) {
                int open_parens = 0;
                for (size_t a = 0; a < arm_cnt; ++a) {
                    const char *a_start = arms[a] + 1, *a_end = (a + 1 < arm_cnt) ? arms[a + 1] : end, *arr = NULL;
                    for (const char *p = a_start; p + 1 < a_end; ++p) if (p[0] == '=' && p[1] == '>') { arr = p; break; }
                    if (!arr) break;
                    const char *pat = a_start; size_t pat_len = (size_t)(arr - a_start);
                    while (pat_len > 0 && isspace((unsigned char)*pat)) { pat++; pat_len--; }
                    while (pat_len > 0 && isspace((unsigned char)pat[pat_len - 1])) pat_len--;
                    if ((pat_len == 1 && pat[0] == '_') || a + 1 == arm_cnt) {
                        emit_norm_lean_slice(out, ir, arr + 2, (size_t)(a_end - (arr + 2)), mode, is_header_inline);
                        break;
                    }
                    fputs("((", out); emit_norm_lean_slice(out, ir, scrut, scrut_len, mode, is_header_inline);
                    fputs(" == ", out); emit_norm_lean_slice(out, ir, pat, pat_len, mode, is_header_inline);
                    fputs(") ? ", out); emit_norm_lean_slice(out, ir, arr + 2, (size_t)(a_end - (arr + 2)), mode, is_header_inline);
                    fputs(" : ", out); open_parens++;
                }
                while (open_parens-- > 0) fputc(')', out);
                return;
            }
        }
    }
    if (is_lean_kw_at(s, s, end, "if", 2)) {
        const char *th = NULL, *el = NULL; int d = 0, pd = 0;
        for (const char *p = s + 2; p < end; ++p) {
            if (*p == '(') pd++; else if (*p == ')' && pd > 0) pd--;
            else if (pd == 0 && is_lean_kw_at(p, s, end, "if", 2)) d++;
            else if (pd == 0 && is_lean_kw_at(p, s, end, "then", 4)) { if (d == 0) { th = p; break; } d--; }
        }
        if (th) {
            d = 0; pd = 0;
            for (const char *p = th + 4; p < end; ++p) {
                if (*p == '(') pd++; else if (*p == ')' && pd > 0) pd--;
                else if (pd == 0 && is_lean_kw_at(p, s, end, "if", 2)) d++;
                else if (pd == 0 && is_lean_kw_at(p, s, end, "else", 4)) { if (d == 0) { el = p; break; } d--; }
            }
        }
        if (th && el) {
            fputc('(', out); emit_norm_lean_slice(out, ir, s + 2, (size_t)(th - (s + 2)), mode, is_header_inline);
            fputs(" ? ", out); emit_norm_lean_slice(out, ir, th + 4, (size_t)(el - (th + 4)), mode, is_header_inline);
            fputs(" : ", out); emit_norm_lean_slice(out, ir, el + 4, (size_t)(end - (el + 4)), mode, is_header_inline); fputc(')', out); return;
        }
    }
    for (int pass = 1; pass <= 10; ++pass) {
        if (pass == 10) {
            int pd = 0;
            for (const char *p = s + 1; p < end; ++p) {
                if (*p == '(') pd++; else if (*p == ')' && pd > 0) pd--;
                if (pd != 0) continue;
                if (p[0] == '^' && p[-1] != '^' && (p + 1 == end || p[1] != '^')) {
                    const char *fn_pow = (mode == LEAN_EXPR_FX64) ? "flow_fx64_pow(" : ((mode == LEAN_EXPR_FLOAT) ? "flow_float_pow(" : ((mode == LEAN_EXPR_INT) ? "flow_int_pow(" : "flow_nat_pow("));
                    fputs(fn_pow, out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                    fputs(", ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                }
            }
            continue;
        }
        int pd = 0;
        for (const char *p = end - 1; p > s; --p) {
            if (*p == ')') pd++; else if (*p == '(' && pd > 0) pd--;
            if (pd != 0) continue;
            if (pass == 1 && p + 1 < end && p[0] == '|' && p[1] == '|' && p[-1] != '|' && (p + 2 == end || p[2] != '|')) {
                fputc('(', out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(" || ", out); emit_norm_lean_slice(out, ir, p + 2, (size_t)(end - (p + 2)), mode, is_header_inline); fputc(')', out); return;
            }
            if (pass == 2 && p + 1 < end && p[0] == '&' && p[1] == '&' && p[-1] != '&' && (p + 2 == end || p[2] != '&')) {
                fputc('(', out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(" && ", out); emit_norm_lean_slice(out, ir, p + 2, (size_t)(end - (p + 2)), mode, is_header_inline); fputc(')', out); return;
            }
            if (pass == 3) {
                if (p + 1 < end && ((p[0] == '=' && p[1] == '=') || (p[0] == '!' && p[1] == '=') || (p[0] == '<' && p[1] == '=' && p[-1] != '<') || (p[0] == '>' && p[1] == '=' && p[-1] != '>'))) {
                    fputc('(', out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fprintf(out, " %c%c ", p[0], p[1]); emit_norm_lean_slice(out, ir, p + 2, (size_t)(end - (p + 2)), mode, is_header_inline); fputc(')', out); return;
                }
                if (p[0] == '<' && p[-1] != '<' && (p + 1 < end && p[1] != '<' && p[1] != '=')) {
                    fputc('(', out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(" < ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                }
                if (p[0] == '>' && p[-1] != '>' && p[-1] != '=' && p[-1] != '-' && (p + 1 < end && p[1] != '>' && p[1] != '=')) {
                    fputc('(', out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(" > ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                }
                if (p[0] == '=' && p[-1] != '=' && p[-1] != '!' && p[-1] != '<' && p[-1] != '>' && p[-1] != ':' && (p + 1 < end && p[1] != '=' && p[1] != '>')) {
                    fputc('(', out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(" == ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                }
            }
            if (pass == 4 && p + 2 < end && p[0] == '|' && p[1] == '|' && p[2] == '|') {
                fputs("((uint64_t)", out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(" | (uint64_t)", out); emit_norm_lean_slice(out, ir, p + 3, (size_t)(end - (p + 3)), mode, is_header_inline); fputc(')', out); return;
            }
            if (pass == 5 && p + 2 < end && p[0] == '^' && p[1] == '^' && p[2] == '^') {
                fputs("((uint64_t)", out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(" ^ (uint64_t)", out); emit_norm_lean_slice(out, ir, p + 3, (size_t)(end - (p + 3)), mode, is_header_inline); fputc(')', out); return;
            }
            if (pass == 6 && p + 2 < end && p[0] == '&' && p[1] == '&' && p[2] == '&') {
                fputs("((uint64_t)", out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(" & (uint64_t)", out); emit_norm_lean_slice(out, ir, p + 3, (size_t)(end - (p + 3)), mode, is_header_inline); fputc(')', out); return;
            }
            if (pass == 7 && p + 2 < end && ((p[0] == '<' && p[1] == '<' && p[2] == '<') || (p[0] == '>' && p[1] == '>' && p[2] == '>'))) {
                fputs("((uint64_t)", out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fprintf(out, " %c%c (uint64_t)", p[0], p[0]); emit_norm_lean_slice(out, ir, p + 3, (size_t)(end - (p + 3)), mode, is_header_inline); fputc(')', out); return;
            }
            if (pass == 8 && (p[0] == '+' || (p[0] == '-' && (p + 1 == end || p[1] != '>')))) {
                const char *l = p - 1; while (l > s && isspace((unsigned char)*l)) --l;
                if ((*l == 'e' || *l == 'E') && l > s && (isdigit((unsigned char)l[-1]) || l[-1] == '.')) continue;
                if (isalnum((unsigned char)*l) || *l == ')' || *l == '_') {
                    const char *ws = l;
                    while (ws > s && (isalnum((unsigned char)ws[-1]) || ws[-1] == '_')) --ws;
                    size_t wl = (size_t)(l - ws + 1);
                    if ((wl == 4 && (!strncmp(ws, "then", 4) || !strncmp(ws, "else", 4) || !strncmp(ws, "with", 4))) ||
                        (wl == 2 && (!strncmp(ws, "in", 2) || !strncmp(ws, "if", 2))) ||
                        (wl == 3 && !strncmp(ws, "let", 3)) ||
                        (wl > 9 && (!strncmp(ws, "flow_nat_", 9) || !strncmp(ws, "flow_float_", 11) || !strncmp(ws, "flow_fx64_", 10))) ||
                        find_ir_lean_fn_len(ir, ws, wl) != NULL)
                        continue;
                    if (mode == LEAN_EXPR_FX64) {
                        fprintf(out, "flow_fx64_%s(", p[0] == '+' ? "add" : "sub");
                        emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(", ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                    }
                    if (mode == LEAN_EXPR_FLOAT) {
                        fprintf(out, "flow_float_%s(", p[0] == '+' ? "add" : "sub");
                        emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(", ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                    }
                    if (p[0] == '+' || mode != LEAN_EXPR_NAT) {
                        fputc('(', out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fprintf(out, " %c ", p[0]); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                    }
                    fputs("flow_nat_sub(", out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(", ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                }
            }
            if (pass == 9 && (p[0] == '*' || p[0] == '/' || p[0] == '%')) {
                if (mode == LEAN_EXPR_FX64) {
                    fprintf(out, "flow_fx64_%s(", p[0] == '*' ? "mul" : (p[0] == '/' ? "div" : "mod"));
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(", ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                }
                if (mode == LEAN_EXPR_FLOAT) {
                    fprintf(out, "flow_float_%s(", p[0] == '*' ? "mul" : (p[0] == '/' ? "div" : "mod"));
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(", ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                }
                if (p[0] == '*') {
                    fputc('(', out); emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fprintf(out, " %c ", p[0]); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
                }
                fprintf(out, "flow_%s_%s(", mode == LEAN_EXPR_INT ? "int" : "nat", p[0] == '/' ? "div" : "mod");
                emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline); fputs(", ", out); emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode, is_header_inline); fputc(')', out); return;
            }
        }
    }
    if (s[0] == '!') {
        fputs("(!", out); emit_norm_lean_slice(out, ir, s + 1, len - 1, mode, is_header_inline); fputc(')', out); return;
    }
    if (s[0] == '-' && len > 1 && s[1] != '>') {
        int has_dot = 0;
        for (size_t i = 1; i < len; ++i) if (s[i] == '.') { has_dot = 1; break; }
        if (mode == LEAN_EXPR_FX64) {
            fputs("flow_fx64_neg(", out); emit_norm_lean_slice(out, ir, s + 1, len - 1, LEAN_EXPR_FX64, is_header_inline); fputc(')', out); return;
        }
        if (mode == LEAN_EXPR_FLOAT || has_dot) {
            fputs("flow_float_neg(", out); emit_norm_lean_slice(out, ir, s + 1, len - 1, LEAN_EXPR_FLOAT, is_header_inline); fputc(')', out); return;
        }
        if (mode == LEAN_EXPR_NAT) { fputs("0ULL", out); return; }
        fputs("(-", out); emit_norm_lean_slice(out, ir, s + 1, len - 1, mode, is_header_inline); fputc(')', out); return;
    }
    if (s[0] == '(') {
        int pd = 0; const char *close_p = NULL;
        for (const char *p = s; p < end; ++p) {
            if (*p == '(') pd++;
            else if (*p == ')' && --pd == 0) { close_p = p; break; }
        }
        if (close_p && close_p + 2 <= end && close_p[1] == '.') {
            int valid_proj = 1;
            for (const char *q = close_p + 2; q < end; ++q)
                if (!isalnum((unsigned char)*q) && *q != '_') { valid_proj = 0; break; }
            if (valid_proj && close_p + 2 < end) {
                fputc('(', out);
                emit_norm_lean_slice(out, ir, s + 1, (size_t)(close_p - (s + 1)), mode, is_header_inline);
                fprintf(out, ").%.*s", (int)(end - (close_p + 2)), close_p + 2);
                return;
            }
        }
    }
    const char *tok_s[FLOW_LEAN_PARAM_MAX + 2]; size_t tok_l[FLOW_LEAN_PARAM_MAX + 2], tok_cnt = 0;
    for (const char *p = s; p < end && tok_cnt < FLOW_LEAN_PARAM_MAX + 2; ) {
        while (p < end && isspace((unsigned char)*p)) ++p;
        if (p >= end) break;
        const char *ts = p;
        if (*p == '(') {
            int pd = 0;
            while (p < end) { if (*p == '(') pd++; else if (*p == ')' && --pd == 0) { ++p; break; } ++p; }
        } else {
            while (p < end && !isspace((unsigned char)*p) && *p != '(' && *p != ')') ++p;
        }
        tok_s[tok_cnt] = ts; tok_l[tok_cnt] = (size_t)(p - ts); tok_cnt++;
    }
    if (tok_cnt > 1) {
        if (tok_l[0] == 6 && !strncmp(tok_s[0], "decide", 6) && tok_cnt == 2) {
            fputs("((bool)", out); emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], mode, is_header_inline); fputc(')', out); return;
        }
        if (tok_l[0] == 13 && !strncmp(tok_s[0], "flow_quantize", 13) && tok_cnt == 5) {
            if (mode == LEAN_EXPR_FX64) {
                fputs("flow_quantize_fx((flow_fx64_t)(", out); emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], LEAN_EXPR_FX64, is_header_inline);
                fputs("), (flow_fx64_t)(", out); emit_norm_lean_slice(out, ir, tok_s[2], tok_l[2], LEAN_EXPR_FX64, is_header_inline);
                fputs("), (flow_fx64_t)(", out); emit_norm_lean_slice(out, ir, tok_s[3], tok_l[3], LEAN_EXPR_FX64, is_header_inline);
                fputs("), (uint32_t)(", out); emit_norm_lean_slice(out, ir, tok_s[4], tok_l[4], LEAN_EXPR_UINT, is_header_inline);
                fputs("))", out); return;
            }
            fputs("flow_quantize((double)(", out); emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], LEAN_EXPR_FLOAT, is_header_inline);
            fputs("), (double)(", out); emit_norm_lean_slice(out, ir, tok_s[2], tok_l[2], LEAN_EXPR_FLOAT, is_header_inline);
            fputs("), (double)(", out); emit_norm_lean_slice(out, ir, tok_s[3], tok_l[3], LEAN_EXPR_FLOAT, is_header_inline);
            fputs("), (uint32_t)(", out); emit_norm_lean_slice(out, ir, tok_s[4], tok_l[4], LEAN_EXPR_UINT, is_header_inline);
            fputs("))", out); return;
        }
        if (tok_l[0] == 15 && !strncmp(tok_s[0], "flow_dequantize", 15) && tok_cnt == 5) {
            if (mode == LEAN_EXPR_FX64) {
                fputs("flow_dequantize_fx((uint64_t)(", out); emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], LEAN_EXPR_UINT, is_header_inline);
                fputs("), (flow_fx64_t)(", out); emit_norm_lean_slice(out, ir, tok_s[2], tok_l[2], LEAN_EXPR_FX64, is_header_inline);
                fputs("), (flow_fx64_t)(", out); emit_norm_lean_slice(out, ir, tok_s[3], tok_l[3], LEAN_EXPR_FX64, is_header_inline);
                fputs("), (uint32_t)(", out); emit_norm_lean_slice(out, ir, tok_s[4], tok_l[4], LEAN_EXPR_UINT, is_header_inline);
                fputs("))", out); return;
            }
            fputs("flow_dequantize((uint64_t)(", out); emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], LEAN_EXPR_UINT, is_header_inline);
            fputs("), (double)(", out); emit_norm_lean_slice(out, ir, tok_s[2], tok_l[2], LEAN_EXPR_FLOAT, is_header_inline);
            fputs("), (double)(", out); emit_norm_lean_slice(out, ir, tok_s[3], tok_l[3], LEAN_EXPR_FLOAT, is_header_inline);
            fputs("), (uint32_t)(", out); emit_norm_lean_slice(out, ir, tok_s[4], tok_l[4], LEAN_EXPR_UINT, is_header_inline);
            fputs("))", out); return;
        }
        if (tok_l[0] > 11 && !strncmp(tok_s[0], "flow_float_", 11)) {
            const char *op_suf = tok_s[0] + 11;
            size_t op_len = tok_l[0] - 11;
            LeanExprMode arg_mode = mode;
            if (op_len == 6 && !strncmp(op_suf, "of_nat", 6)) arg_mode = LEAN_EXPR_UINT;
            else if (op_len == 6 && !strncmp(op_suf, "of_int", 6)) arg_mode = LEAN_EXPR_INT;
            if (mode == LEAN_EXPR_FX64) fprintf(out, "flow_fx64_%.*s(", (int)op_len, op_suf);
            else fprintf(out, "%.*s(", (int)tok_l[0], tok_s[0]);
            for (size_t ti = 1; ti < tok_cnt; ++ti) {
                if (ti > 1) fputs(", ", out);
                emit_norm_lean_slice(out, ir, tok_s[ti], tok_l[ti], arg_mode, is_header_inline);
            }
            fputc(')', out); return;
        }
        const FlowLeanFunction *callee = find_ir_lean_fn_len(ir, tok_s[0], tok_l[0]);
        int use_fx = (callee && mode == LEAN_EXPR_FX64 && !(ir && ir->float_abi_ieee64) && infer_fn_expr_mode(callee) == LEAN_EXPR_FLOAT);
        fprintf(out, "%s%.*s%s(", (callee && is_header_inline) ? "flowc_" : "", (int)tok_l[0], tok_s[0], use_fx ? "_fx" : "");
        for (size_t ti = 1; ti < tok_cnt; ++ti) {
            if (ti > 1) fputs(", ", out);
            emit_norm_lean_slice(out, ir, tok_s[ti], tok_l[ti], mode, is_header_inline);
        }
        fputc(')', out); return;
    }
    if (len > 10 && s[0] == '0' && (s[1] == 'x' || s[1] == 'X') && isxdigit((unsigned char)s[len - 1])) {
        fprintf(out, "%.*sULL", (int)len, s); return;
    }
    if (mode == LEAN_EXPR_FX64 && len > 0 && len < 64 && isdigit((unsigned char)s[0])) {
        char nbuf[64];
        memcpy(nbuf, s, len);
        nbuf[len] = '\0';
        char *ep = NULL;
        double d = strtod(nbuf, &ep);
        if (ep && *ep == '\0') {
            flow_fx64_t fx = flow_fx64_from_double(d);
            if (fx == INT64_MIN) fputs("FLOW_FX64_NONE", out);
            else fprintf(out, "INT64_C(%lld)", (long long)fx);
            return;
        }
    }
    fprintf(out, "%.*s", (int)len, s);
}
static void emit_lean_expr_as_c_ex(FILE *out, const SemanticIR *ir, const char *expr, LeanExprMode mode, int is_header_inline) {
    static const struct { const char *lean_fn; size_t l_len; const char *c_fn; size_t c_len; } BUILTIN_MAP[] = {
        {"Nat.min", 7, "flow_nat_min", 12}, {"Nat.max", 7, "flow_nat_max", 12}, {"Float.abs", 9, "flow_float_abs", 14}, {"Float.floor", 11, "flow_float_floor", 16},
        {"Float.ceil", 10, "flow_float_ceil", 15}, {"Float.round", 11, "flow_float_round", 16}, {"Float.sqrt", 10, "flow_float_sqrt", 15}, {"Float.exp", 9, "flow_float_exp", 14},
        {"Float.log", 9, "flow_float_log", 14}, {"Float.sin", 9, "flow_float_sin", 14}, {"Float.cos", 9, "flow_float_cos", 14}, {"Float.atan2", 11, "flow_float_atan2", 16},
        {"Float.pow", 9, "flow_float_pow", 14}, {"Float.max", 9, "flow_float_max", 14}, {"Float.min", 9, "flow_float_min", 14}, {"Float.ofNat", 11, "flow_float_of_nat", 17},
        {"Float.ofInt", 11, "flow_float_of_int", 17}, {"Real.abs", 8, "flow_float_abs", 14}, {"Real.floor", 10, "flow_float_floor", 16}, {"Real.ceil", 9, "flow_float_ceil", 15},
        {"Real.round", 10, "flow_float_round", 16}, {"Real.sqrt", 9, "flow_float_sqrt", 15}, {"Real.exp", 8, "flow_float_exp", 14}, {"Real.log", 8, "flow_float_log", 14},
        {"Real.sin", 8, "flow_float_sin", 14}, {"Real.cos", 8, "flow_float_cos", 14}, {"Real.atan2", 10, "flow_float_atan2", 16}, {"Real.pow", 8, "flow_float_pow", 14},
        {"Real.max", 8, "flow_float_max", 14}, {"Real.min", 8, "flow_float_min", 14}, {"f_abs", 5, "flow_float_abs", 14}, {"f_max", 5, "flow_float_max", 14}, {"f_min", 5, "flow_float_min", 14}
    };
    char norm[4096]; size_t j = 0;
    for (size_t i = 0; expr[i] && j + 20 < sizeof(norm); ) {
        if (!strncmp(expr + i, "\xe2\x89\xa4", 3)) { norm[j++] = '<'; norm[j++] = '='; i += 3; continue; }
        if (!strncmp(expr + i, "\xe2\x89\xa5", 3)) { norm[j++] = '>'; norm[j++] = '='; i += 3; continue; }
        if (!strncmp(expr + i, "\xe2\x89\xa0", 3)) { norm[j++] = '!'; norm[j++] = '='; i += 3; continue; }
        if (!strncmp(expr + i, "\xe2\x88\xa7", 3)) { norm[j++] = '&'; norm[j++] = '&'; i += 3; continue; }
        if (!strncmp(expr + i, "\xe2\x88\xa8", 3)) { norm[j++] = '|'; norm[j++] = '|'; i += 3; continue; }
        if (!strncmp(expr + i, "\xc2\xac", 2)) { norm[j++] = '!'; i += 2; continue; }
        int mapped = 0;
        for (size_t bi = 0; bi < sizeof(BUILTIN_MAP) / sizeof(BUILTIN_MAP[0]); ++bi) {
            size_t ll = BUILTIN_MAP[bi].l_len;
            if (!strncmp(expr + i, BUILTIN_MAP[bi].lean_fn, ll) && !isalnum((unsigned char)expr[i + ll]) && expr[i + ll] != '_') {
                memcpy(norm + j, BUILTIN_MAP[bi].c_fn, BUILTIN_MAP[bi].c_len);
                j += BUILTIN_MAP[bi].c_len;
                i += ll;
                mapped = 1;
                break;
            }
        }
        if (mapped) continue;
        norm[j++] = expr[i++];
    }
    norm[j] = '\0'; emit_norm_lean_slice(out, ir, norm, j, mode, is_header_inline);
}
