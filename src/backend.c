static int body_has_ident_tok(const char *s, const char *ident) {
    if (!s || !ident || !ident[0])
        return 0;
    size_t ilen = strlen(ident);
    for (const char *p = strstr(s, ident); p; p = strstr(p + 1, ident)) {
        int l_ok = (p == s) || (!isalnum((unsigned char)p[-1]) && p[-1] != '_' && p[-1] != '.');
        int r_ok = !isalnum((unsigned char)p[ilen]) && p[ilen] != '_' && p[ilen] != '.';
        if (l_ok && r_ok)
            return 1;
    }
    return 0;
}
static int is_jet2_eligible_fn(const SemanticIR *ir, const FlowLeanFunction *fn) {
    (void)ir;
    return fn && ((fn->variant_mask & FLOW_FN_VAR_JET2) != 0);
}
static size_t split_comma_slices(const char *s, size_t len, const char **out_s, size_t *out_l,
                                 size_t max_parts) {
    const char *end = s + len, *cur = s;
    size_t cnt = 0;
    int pd = 0;
    for (const char *p = s; p <= end && cnt < max_parts; ++p) {
        if (p < end && *p == '(')
            pd++;
        else if (p < end && *p == ')' && pd > 0)
            pd--;
        else if (p == end || (pd == 0 && *p == ',')) {
            const char *ps = cur, *pe = p;
            while (ps < pe && isspace((unsigned char)*ps))
                ++ps;
            while (pe > ps && isspace((unsigned char)pe[-1]))
                --pe;
            if (pe - ps >= 2 && ps[0] == '(' && pe[-1] == ')') {
                int d = 0, w = 1;
                for (const char *q = ps; q + 1 < pe; ++q) {
                    if (*q == '(')
                        d++;
                    else if (*q == ')' && --d == 0) {
                        w = 0;
                        break;
                    }
                }
                if (w) {
                    ++ps;
                    --pe;
                    while (ps < pe && isspace((unsigned char)*ps))
                        ++ps;
                    while (pe > ps && isspace((unsigned char)pe[-1]))
                        --pe;
                }
            }
            out_s[cnt] = ps;
            out_l[cnt] = (size_t)(pe - ps);
            cnt++;
            cur = p + 1;
        }
    }
    return cnt;
}
static const FlowLeanFunction *find_ir_lean_fn_len(const SemanticIR *ir, const char *name,
                                                   size_t len) {
    if (!ir || !name || !len)
        return NULL;
    for (size_t i = 0; i < ir->lean_function_count; ++i)
        if (strlen(ir->lean_functions[i].name) == len &&
            !strncmp(ir->lean_functions[i].name, name, len))
            return &ir->lean_functions[i];
    return NULL;
}
static int parse_result_match_pattern(const char *pt_s, size_t pt_l, int *is_some_out,
                                      char *bound_var_out, size_t var_max) {
    if (is_some_out)
        *is_some_out = 0;
    if (bound_var_out && var_max > 0)
        bound_var_out[0] = '\0';
    while (pt_l > 0 && isspace((unsigned char)*pt_s)) {
        ++pt_s;
        --pt_l;
    }
    while (pt_l > 0 && isspace((unsigned char)pt_s[pt_l - 1]))
        --pt_l;
    while (pt_l >= 2 && pt_s[0] == '(' && pt_s[pt_l - 1] == ')') {
        ++pt_s;
        pt_l -= 2;
        while (pt_l > 0 && isspace((unsigned char)*pt_s)) {
            ++pt_s;
            --pt_l;
        }
        while (pt_l > 0 && isspace((unsigned char)pt_s[pt_l - 1]))
            --pt_l;
    }
    if ((pt_l == 4 && !strncmp(pt_s, "none", 4)) || (pt_l == 8 && !strncmp(pt_s, "boundary", 8))) {
        if (is_some_out)
            *is_some_out = 0;
        return 1;
    }
    size_t clen = 0;
    int is_some = 0;
    if (pt_l > 5 && !strncmp(pt_s, "some", 4) && isspace((unsigned char)pt_s[4])) {
        clen = 4;
        is_some = 1;
    } else if (pt_l > 9 && !strncmp(pt_s, "interior", 8) && isspace((unsigned char)pt_s[8])) {
        clen = 8;
        is_some = 1;
    } else if (pt_l > 6 && !strncmp(pt_s, "point", 5) && isspace((unsigned char)pt_s[5])) {
        clen = 5;
        is_some = 1;
    } else if (pt_l > 9 && !strncmp(pt_s, "boundary", 8) && isspace((unsigned char)pt_s[8])) {
        clen = 8;
        is_some = 0;
    }
    if (clen == 0)
        return 0;
    if (is_some_out)
        *is_some_out = is_some;
    const char *vs = pt_s + clen, *ve = pt_s + pt_l;
    while (vs < ve && isspace((unsigned char)*vs))
        ++vs;
    while (ve > vs && isspace((unsigned char)ve[-1]))
        --ve;
    if (ve > vs && !(ve - vs == 1 && vs[0] == '_') && bound_var_out && var_max > 0) {
        size_t vl = (size_t)(ve - vs);
        if (vl >= var_max)
            vl = var_max - 1;
        memcpy(bound_var_out, vs, vl);
        bound_var_out[vl] = '\0';
    }
    return 1;
}
static int split_lean_let_slice(const char *s, const char *end, const char **ps_out,
                                const char **pe_out, const char **rhs_out, const char **rhs_end_out,
                                const char **rest_out) {
    if (!is_lean_kw_at(s, s, end, "let", 3))
        return 0;
    const char *ce = NULL;
    int pd = 0;
    for (const char *p = s + 3; p + 1 < end; ++p) {
        if (*p == '(')
            pd++;
        else if (*p == ')' && pd > 0)
            pd--;
        else if (pd == 0 && p[0] == ':' && p[1] == '=') {
            ce = p;
            break;
        }
    }
    if (!ce)
        return 0;
    const char *rhs = ce + 2;
    while (rhs < end && isspace((unsigned char)*rhs))
        ++rhs;
    const char *rhs_end = NULL, *rest = NULL;
    pd = 0;
    int ld = 0;
    for (const char *p = rhs; p < end; ++p) {
        if (*p == '(')
            pd++;
        else if (*p == ')' && pd > 0)
            pd--;
        else if (pd == 0 && is_lean_kw_at(p, rhs, end, "let", 3))
            ld++;
        else if (pd == 0 && is_lean_kw_at(p, rhs, end, "in", 2)) {
            if (ld == 0) {
                rhs_end = p;
                rest = p + 2;
                break;
            }
            ld--;
        }
    }
    if (!rhs_end) {
        pd = 0;
        int id = 0;
        for (const char *p = rhs; p < end; ++p) {
            if (*p == '(')
                pd++;
            else if (*p == ')' && pd > 0)
                pd--;
            else if (pd == 0 && is_lean_kw_at(p, rhs, end, "if", 2))
                id++;
            else if (pd == 0 && is_lean_kw_at(p, rhs, end, "else", 4) && id > 0)
                id--;
            else if (pd == 0 && id == 0 && (*p == '\n' || *p == ';')) {
                rhs_end = p;
                rest = p + 1;
                break;
            }
        }
    }
    if (!rhs_end || !rest)
        return 0;
    while (rhs_end > rhs && isspace((unsigned char)rhs_end[-1]))
        --rhs_end;
    while (rest < end && isspace((unsigned char)*rest))
        ++rest;
    if (is_lean_kw_at(rest, rest, end, "in", 2)) {
        rest += 2;
        while (rest < end && isspace((unsigned char)*rest))
            ++rest;
    }
    const char *ps = s + 3, *pe = ce;
    while (ps < pe && isspace((unsigned char)*ps))
        ++ps;
    while (pe > ps && isspace((unsigned char)pe[-1]))
        --pe;
    *ps_out = ps;
    *pe_out = pe;
    *rhs_out = rhs;
    *rhs_end_out = rhs_end;
    *rest_out = rest;
    return 1;
}
static int split_lean_if_slice(const char *s, const char *end, const char **th_out,
                               const char **el_out) {
    if (!is_lean_kw_at(s, s, end, "if", 2))
        return 0;
    const char *th = NULL, *el = NULL;
    int d = 0, pd = 0;
    for (const char *p = s + 2; p < end; ++p) {
        if (*p == '(')
            pd++;
        else if (*p == ')' && pd > 0)
            pd--;
        else if (pd == 0 && is_lean_kw_at(p, s, end, "if", 2))
            d++;
        else if (pd == 0 && is_lean_kw_at(p, s, end, "then", 4)) {
            if (d == 0) {
                th = p;
                break;
            }
            d--;
        }
    }
    if (!th)
        return 0;
    d = 0;
    pd = 0;
    for (const char *p = th + 4; p < end; ++p) {
        if (*p == '(')
            pd++;
        else if (*p == ')' && pd > 0)
            pd--;
        else if (pd == 0 && is_lean_kw_at(p, s, end, "if", 2))
            d++;
        else if (pd == 0 && is_lean_kw_at(p, s, end, "else", 4)) {
            if (d == 0) {
                el = p;
                break;
            }
            d--;
        }
    }
    if (!el)
        return 0;
    *th_out = th;
    *el_out = el;
    return 1;
}
static int split_lean_match_slice(const char *s, const char *end, const char **w_out,
                                  const char **arms_out, size_t *arm_cnt_out, size_t max_arms) {
    if (!is_lean_kw_at(s, s, end, "match", 5))
        return 0;
    const char *w = NULL;
    int pd = 0;
    for (const char *p = s + 5; p < end; ++p) {
        if (*p == '(')
            pd++;
        else if (*p == ')' && pd > 0)
            pd--;
        else if (pd == 0 && is_lean_kw_at(p, s, end, "with", 4)) {
            w = p;
            break;
        }
    }
    if (!w)
        return 0;
    size_t arm_cnt = 0;
    pd = 0;
    int md = 0;
    for (const char *p = w + 4; p < end; ++p) {
        if (*p == '(')
            pd++;
        else if (*p == ')' && pd > 0)
            pd--;
        else if (pd == 0 && is_lean_kw_at(p, w + 4, end, "match", 5))
            md++;
        else if (pd == 0 && md == 0 && *p == '|' && (p == w + 4 || p[-1] != '|') &&
                 (p + 1 == end || p[1] != '|')) {
            if (arm_cnt < max_arms)
                arms_out[arm_cnt++] = p;
        }
    }
    *w_out = w;
    *arm_cnt_out = arm_cnt;
    return arm_cnt > 0;
}
static int is_slice_nat_expr(const SemanticIR *ir, const char *s, size_t len) {
    if (!ir || !s || len == 0)
        return 0;
    while (len > 0 && isspace((unsigned char)*s)) {
        s++;
        len--;
    }
    while (len > 0 && isspace((unsigned char)s[len - 1]))
        len--;
    if (len == 0)
        return 0;
    char tok[FLOW_NAME] = {0};
    size_t tl = 0;
    for (size_t i = 0; i < len && tl + 1 < sizeof(tok); ++i) {
        if (isalnum((unsigned char)s[i]) || s[i] == '_')
            tok[tl++] = s[i];
        else
            break;
    }
    tok[tl] = '\0';
    if (tok[0]) {
        for (size_t fi = 0; fi < ir->lean_function_count; ++fi) {
            const FlowLeanFunction *fn = &ir->lean_functions[fi];
            for (size_t pi = 0; pi < fn->param_count; ++pi) {
                if (!strcmp(fn->param_names[pi], tok)) {
                    if (!strcmp(fn->param_types[pi], "Nat"))
                        return 1;
                    if (!strncmp(fn->param_types[pi], "Int", 3))
                        return 0;
                }
            }
        }
    }
    int all_digits = 1;
    for (size_t i = 0; i < len; ++i) {
        if (!isdigit((unsigned char)s[i])) {
            all_digits = 0;
            break;
        }
    }
    if (all_digits)
        return 1;
    return 0;
}
static void emit_norm_lean_slice(FILE *out, const SemanticIR *ir, const char *s, size_t len,
                                 LeanExprMode mode, int is_header_inline) {
    for (;;) {
        while (len > 0 && isspace((unsigned char)*s)) {
            s++;
            len--;
        }
        while (len > 0 && isspace((unsigned char)s[len - 1]))
            len--;
        if (len >= 2 && s[0] == '(' && s[len - 1] == ')') {
            int d = 0, wrapped = 1;
            for (size_t i = 0; i + 1 < len; ++i) {
                if (s[i] == '(')
                    d++;
                else if (s[i] == ')') {
                    if (--d == 0) {
                        wrapped = 0;
                        break;
                    }
                }
            }
            if (wrapped) {
                s++;
                len -= 2;
                continue;
            }
        }
        break;
    }
    if (len == 0) {
        fputs(mode == LEAN_EXPR_JET2 ? "flow_jet2_const(0.0)" : "0", out);
        return;
    }
    const char *end = s + len;
    const char *l_ps = NULL, *l_pe = NULL, *l_rhs = NULL, *l_rhs_end = NULL, *l_rest = NULL;
    if (split_lean_let_slice(s, end, &l_ps, &l_pe, &l_rhs, &l_rhs_end, &l_rest)) {
        char var[FLOW_NAME] = {0};
        size_t k = 0;
        for (const char *p = l_ps; p < l_pe && *p != ':'; ++p)
            if (!isspace((unsigned char)*p) && k + 1 < sizeof(var))
                var[k++] = *p;
        char sub[8192];
        subst_lean_var(l_rest, (size_t)(end - l_rest), var, l_rhs, (size_t)(l_rhs_end - l_rhs), sub,
                       sizeof(sub));
        emit_norm_lean_slice(out, ir, sub, strlen(sub), mode, is_header_inline);
        return;
    }
    const char *w = NULL, *arms[64];
    size_t arm_cnt = 0;
    if (split_lean_match_slice(s, end, &w, arms, &arm_cnt, 64)) {
        const char *sc_s[4];
        size_t sc_l[4], sc_cnt = split_comma_slices(s + 5, (size_t)(w - (s + 5)), sc_s, sc_l, 4);
        if (sc_cnt > 0) {
            int open_parens = 0;
            for (size_t a = 0; a < arm_cnt; ++a) {
                const char *a_start = arms[a] + 1, *a_end = (a + 1 < arm_cnt) ? arms[a + 1] : end,
                           *arr = NULL;
                for (const char *p = a_start; p + 1 < a_end; ++p)
                    if (p[0] == '=' && p[1] == '>') {
                        arr = p;
                        break;
                    }
                if (!arr)
                    break;
                const char *pt_s[4];
                size_t pt_l[4],
                    pt_cnt = split_comma_slices(a_start, (size_t)(arr - a_start), pt_s, pt_l, 4);
                char arm_body_buf[4096];
                const char *arm_body_s = arr + 2;
                size_t arm_body_l = (size_t)(a_end - (arr + 2));
                int all_wild = 1;
                for (size_t m = 0; m < pt_cnt && m < sc_cnt; ++m) {
                    int res_some = 0;
                    char bound_var[FLOW_NAME] = {0};
                    if (parse_result_match_pattern(pt_s[m], pt_l[m], &res_some, bound_var,
                                                   sizeof(bound_var))) {
                        all_wild = 0;
                        if (bound_var[0]) {
                            if (!res_some) {
                                char bcode_expr[256];
                                snprintf(bcode_expr, sizeof(bcode_expr),
                                         "flowc_boundary_tag_code((uint64_t)(%.*s))", (int)sc_l[m],
                                         sc_s[m]);
                                subst_lean_var(arm_body_s, arm_body_l, bound_var, bcode_expr,
                                               strlen(bcode_expr), arm_body_buf,
                                               sizeof(arm_body_buf));
                            } else {
                                subst_lean_var(arm_body_s, arm_body_l, bound_var, sc_s[m], sc_l[m],
                                               arm_body_buf, sizeof(arm_body_buf));
                            }
                            arm_body_s = arm_body_buf;
                            arm_body_l = strlen(arm_body_buf);
                        }
                    } else if (!(pt_l[m] == 1 && pt_s[m][0] == '_')) {
                        all_wild = 0;
                    }
                }
                if (all_wild || a + 1 == arm_cnt) {
                    emit_norm_lean_slice(out, ir, arm_body_s, arm_body_l, mode, is_header_inline);
                    break;
                }
                fputs("((", out);
                int seen_cond = 0;
                for (size_t m = 0; m < pt_cnt && m < sc_cnt; ++m) {
                    if (pt_l[m] == 1 && pt_s[m][0] == '_')
                        continue;
                    if (seen_cond)
                        fputs(" && ", out);
                    int res_some = 0;
                    char bound_var[FLOW_NAME] = {0};
                    if (parse_result_match_pattern(pt_s[m], pt_l[m], &res_some, bound_var,
                                                   sizeof(bound_var))) {
                        fputs(res_some ? "(!flowc_is_boundary_tag((uint64_t)("
                                       : "(flowc_is_boundary_tag((uint64_t)(",
                              out);
                        emit_norm_lean_slice(out, ir, sc_s[m], sc_l[m], mode, is_header_inline);
                        fputs(")))", out);
                    } else {
                        fputc('(', out);
                        emit_norm_lean_slice(out, ir, sc_s[m], sc_l[m], mode, is_header_inline);
                        fputs(" == ", out);
                        emit_norm_lean_slice(out, ir, pt_s[m], pt_l[m], mode, is_header_inline);
                        fputc(')', out);
                    }
                    seen_cond = 1;
                }
                fputs(") ? ", out);
                emit_norm_lean_slice(out, ir, arm_body_s, arm_body_l, mode, is_header_inline);
                fputs(" : ", out);
                open_parens++;
            }
            while (open_parens-- > 0)
                fputc(')', out);
            return;
        }
    }
    const char *th = NULL, *el = NULL;
    if (split_lean_if_slice(s, end, &th, &el)) {
        fputc('(', out);
        emit_norm_lean_slice(out, ir, s + 2, (size_t)(th - (s + 2)), mode, is_header_inline);
        fputs(" ? ", out);
        emit_norm_lean_slice(out, ir, th + 4, (size_t)(el - (th + 4)), mode, is_header_inline);
        fputs(" : ", out);
        emit_norm_lean_slice(out, ir, el + 4, (size_t)(end - (el + 4)), mode, is_header_inline);
        fputc(')', out);
        return;
    }
    for (int pass = -1; pass <= 10; ++pass) {
        if (pass == 0) {
            int pd = 0;
            for (const char *p = s; p + 1 < end; ++p) {
                if (*p == '(')
                    pd++;
                else if (*p == ')' && pd > 0)
                    pd--;
                if (pd != 0 || p == s)
                    continue;
                if (p[0] == '-' && p[1] == '>' && p[-1] != '<') {
                    fputs("((!", out);
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                    fputs(") || (", out);
                    emit_norm_lean_slice(out, ir, p + 2, (size_t)(end - (p + 2)), mode,
                                         is_header_inline);
                    fputs("))", out);
                    return;
                }
            }
            continue;
        }
        if (pass == 10) {
            int pd = 0;
            for (const char *p = s; p < end; ++p) {
                if (*p == '(')
                    pd++;
                else if (*p == ')' && pd > 0)
                    pd--;
                if (pd != 0 || p == s)
                    continue;
                if (p[0] == '^' && p[-1] != '^' && (p + 1 == end || p[1] != '^')) {
                    const char *fn_pow =
                        (mode == LEAN_EXPR_JET2)
                            ? "flow_jet2_pow("
                            : ((mode == LEAN_EXPR_INT) ? "flow_int_pow(" : "flow_nat_pow(");
                    fputs(fn_pow, out);
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                    fputs(", ", out);
                    emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode,
                                         is_header_inline);
                    fputc(')', out);
                    return;
                }
            }
            continue;
        }
        int pd = 0;
        for (const char *p = end - 1; p > s; --p) {
            if (*p == ')')
                pd++;
            else if (*p == '(' && pd > 0)
                pd--;
            if (pd != 0)
                continue;
            if (pass == -1 && p + 2 < end && p[0] == '<' && p[1] == '-' && p[2] == '>') {
                fputs("((bool)(", out);
                emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                fputs(") == (bool)(", out);
                emit_norm_lean_slice(out, ir, p + 3, (size_t)(end - (p + 3)), mode,
                                     is_header_inline);
                fputs("))", out);
                return;
            }
            if (pass == 1 && p + 1 < end && p[0] == '|' && p[1] == '|' && p[-1] != '|' &&
                (p + 2 == end || p[2] != '|')) {
                fputc('(', out);
                emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                fputs(" || ", out);
                emit_norm_lean_slice(out, ir, p + 2, (size_t)(end - (p + 2)), mode,
                                     is_header_inline);
                fputc(')', out);
                return;
            }
            if (pass == 2 && p + 1 < end && p[0] == '&' && p[1] == '&' && p[-1] != '&' &&
                (p + 2 == end || p[2] != '&')) {
                fputc('(', out);
                emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                fputs(" && ", out);
                emit_norm_lean_slice(out, ir, p + 2, (size_t)(end - (p + 2)), mode,
                                     is_header_inline);
                fputc(')', out);
                return;
            }
            if (pass == 3) {
                const char *v_suf = (mode == LEAN_EXPR_JET2) ? ").v" : "";
                const char *v_pre = (mode == LEAN_EXPR_JET2) ? "(" : "";
                if (p + 1 < end && ((p[0] == '=' && p[1] == '=') || (p[0] == '!' && p[1] == '=') ||
                                    (p[0] == '<' && p[1] == '=' && p[-1] != '<') ||
                                    (p[0] == '>' && p[1] == '=' && p[-1] != '>'))) {
                    fprintf(out, "(%s", v_pre);
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                    fprintf(out, "%s %c%c %s", v_suf, p[0], p[1], v_pre);
                    emit_norm_lean_slice(out, ir, p + 2, (size_t)(end - (p + 2)), mode,
                                         is_header_inline);
                    fprintf(out, "%s)", v_suf);
                    return;
                }
                if (p[0] == '<' && p[-1] != '<' && (p + 1 < end && p[1] != '<' && p[1] != '=')) {
                    fprintf(out, "(%s", v_pre);
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                    fprintf(out, "%s < %s", v_suf, v_pre);
                    emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode,
                                         is_header_inline);
                    fprintf(out, "%s)", v_suf);
                    return;
                }
                if (p[0] == '>' && p[-1] != '>' && p[-1] != '=' && p[-1] != '-' &&
                    (p + 1 < end && p[1] != '>' && p[1] != '=')) {
                    fprintf(out, "(%s", v_pre);
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                    fprintf(out, "%s > %s", v_suf, v_pre);
                    emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode,
                                         is_header_inline);
                    fprintf(out, "%s)", v_suf);
                    return;
                }
                if (p[0] == '=' && p[-1] != '=' && p[-1] != '!' && p[-1] != '<' && p[-1] != '>' &&
                    p[-1] != ':' && (p + 1 < end && p[1] != '=' && p[1] != '>')) {
                    fprintf(out, "(%s", v_pre);
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                    fprintf(out, "%s == %s", v_suf, v_pre);
                    emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode,
                                         is_header_inline);
                    fprintf(out, "%s)", v_suf);
                    return;
                }
            }
            if (pass == 4 && p + 2 < end && p[0] == '|' && p[1] == '|' && p[2] == '|') {
                fputs("((uint64_t)", out);
                emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                fputs(" | (uint64_t)", out);
                emit_norm_lean_slice(out, ir, p + 3, (size_t)(end - (p + 3)), mode,
                                     is_header_inline);
                fputc(')', out);
                return;
            }
            if (pass == 5 && p + 2 < end && p[0] == '^' && p[1] == '^' && p[2] == '^') {
                fputs("((uint64_t)", out);
                emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                fputs(" ^ (uint64_t)", out);
                emit_norm_lean_slice(out, ir, p + 3, (size_t)(end - (p + 3)), mode,
                                     is_header_inline);
                fputc(')', out);
                return;
            }
            if (pass == 6 && p + 2 < end && p[0] == '&' && p[1] == '&' && p[2] == '&') {
                fputs("((uint64_t)", out);
                emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                fputs(" & (uint64_t)", out);
                emit_norm_lean_slice(out, ir, p + 3, (size_t)(end - (p + 3)), mode,
                                     is_header_inline);
                fputc(')', out);
                return;
            }
            if (pass == 7 && p + 2 < end &&
                ((p[0] == '<' && p[1] == '<' && p[2] == '<') ||
                 (p[0] == '>' && p[1] == '>' && p[2] == '>'))) {
                fputs("((uint64_t)", out);
                emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                fprintf(out, " %c%c (uint64_t)", p[0], p[0]);
                emit_norm_lean_slice(out, ir, p + 3, (size_t)(end - (p + 3)), mode,
                                     is_header_inline);
                fputc(')', out);
                return;
            }
            if (pass == 8 && (p[0] == '+' || (p[0] == '-' && (p + 1 == end || p[1] != '>')))) {
                const char *l = p - 1;
                while (l > s && isspace((unsigned char)*l))
                    --l;
                if ((*l == 'e' || *l == 'E') && l > s &&
                    (isdigit((unsigned char)l[-1]) || l[-1] == '.'))
                    continue;
                if (isalnum((unsigned char)*l) || *l == ')' || *l == '_') {
                    const char *ws = l;
                    while (ws > s && (isalnum((unsigned char)ws[-1]) || ws[-1] == '_'))
                        --ws;
                    size_t wl = (size_t)(l - ws + 1);
                    if ((wl == 4 && (!strncmp(ws, "then", 4) || !strncmp(ws, "else", 4) ||
                                     !strncmp(ws, "with", 4))) ||
                        (wl == 2 && (!strncmp(ws, "in", 2) || !strncmp(ws, "if", 2))) ||
                        (wl == 3 && !strncmp(ws, "let", 3)) ||
                        (wl > 9 &&
                         (!strncmp(ws, "flow_nat_", 9) || !strncmp(ws, "flow_float_", 11) ||
                          !strncmp(ws, "flow_jet2_", 10))) ||
                        find_ir_lean_fn_len(ir, ws, wl) != NULL)
                        continue;
                    if (mode == LEAN_EXPR_JET2) {
                        fprintf(out, "flow_jet2_%s(", p[0] == '+' ? "add" : "sub");
                        emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                        fputs(", ", out);
                        emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode,
                                             is_header_inline);
                        fputc(')', out);
                        return;
                    }
                    int is_nat_op = (mode == LEAN_EXPR_NAT);
                    if (!is_nat_op && p[0] == '-') {
                        is_nat_op = is_slice_nat_expr(ir, s, (size_t)(p - s));
                    }
                    if (p[0] == '+' || !is_nat_op) {
                        fputc('(', out);
                        emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                        fprintf(out, " %c ", p[0]);
                        emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode,
                                             is_header_inline);
                        fputc(')', out);
                        return;
                    }
                    fputs("flow_nat_sub(", out);
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), LEAN_EXPR_NAT,
                                         is_header_inline);
                    fputs(", ", out);
                    emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), LEAN_EXPR_NAT,
                                         is_header_inline);
                    fputc(')', out);
                    return;
                }
            }
            if (pass == 9 && (p[0] == '*' || p[0] == '/' || p[0] == '%')) {
                if (mode == LEAN_EXPR_JET2) {
                    fprintf(out, "flow_jet2_%s(",
                            p[0] == '*' ? "mul" : (p[0] == '/' ? "div" : "mod"));
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                    fputs(", ", out);
                    emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode,
                                         is_header_inline);
                    fputc(')', out);
                    return;
                }
                if (p[0] == '*') {
                    fputc('(', out);
                    emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                    fprintf(out, " %c ", p[0]);
                    emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode,
                                         is_header_inline);
                    fputc(')', out);
                    return;
                }
                fprintf(out, "flow_%s_%s(", mode == LEAN_EXPR_INT ? "int" : "nat",
                        p[0] == '/' ? "div" : "mod");
                emit_norm_lean_slice(out, ir, s, (size_t)(p - s), mode, is_header_inline);
                fputs(", ", out);
                emit_norm_lean_slice(out, ir, p + 1, (size_t)(end - (p + 1)), mode,
                                     is_header_inline);
                fputc(')', out);
                return;
            }
        }
    }
    if (s[0] == '!') {
        fputs("(!", out);
        emit_norm_lean_slice(out, ir, s + 1, len - 1, mode, is_header_inline);
        fputc(')', out);
        return;
    }
    if (s[0] == '-' && len > 1 && s[1] != '>') {
        if (mode == LEAN_EXPR_JET2) {
            fputs("flow_jet2_neg(", out);
            emit_norm_lean_slice(out, ir, s + 1, len - 1, LEAN_EXPR_JET2, is_header_inline);
            fputc(')', out);
            return;
        }
        if (mode == LEAN_EXPR_NAT) {
            fputs("0ULL", out);
            return;
        }
        fputs("(-", out);
        emit_norm_lean_slice(out, ir, s + 1, len - 1, mode, is_header_inline);
        fputc(')', out);
        return;
    }
    if (s[0] == '(') {
        int pd = 0;
        const char *close_p = NULL;
        for (const char *p = s; p < end; ++p) {
            if (*p == '(')
                pd++;
            else if (*p == ')' && --pd == 0) {
                close_p = p;
                break;
            }
        }
        if (close_p && close_p + 2 <= end && close_p[1] == '.') {
            int valid_proj = 1;
            for (const char *q = close_p + 2; q < end; ++q)
                if (!isalnum((unsigned char)*q) && *q != '_') {
                    valid_proj = 0;
                    break;
                }
            if (valid_proj && close_p + 2 < end) {
                fputc('(', out);
                emit_norm_lean_slice(out, ir, s + 1, (size_t)(close_p - (s + 1)), mode,
                                     is_header_inline);
                fprintf(out, ").%.*s", (int)(end - (close_p + 2)), close_p + 2);
                return;
            }
        }
    }
    const char *tok_s[FLOW_LEAN_PARAM_MAX + 2];
    size_t tok_l[FLOW_LEAN_PARAM_MAX + 2], tok_cnt = 0;
    for (const char *p = s; p < end && tok_cnt < FLOW_LEAN_PARAM_MAX + 2;) {
        while (p < end && isspace((unsigned char)*p))
            ++p;
        if (p >= end)
            break;
        const char *ts = p;
        if (*p == '(') {
            int pd = 0;
            while (p < end) {
                if (*p == '(')
                    pd++;
                else if (*p == ')' && --pd == 0) {
                    ++p;
                    break;
                }
                ++p;
            }
        } else {
            while (p < end && !isspace((unsigned char)*p) && *p != '(' && *p != ')')
                ++p;
        }
        tok_s[tok_cnt] = ts;
        tok_l[tok_cnt] = (size_t)(p - ts);
        tok_cnt++;
    }
    if (tok_cnt > 1) {
        if (tok_l[0] == 3 && !strncmp(tok_s[0], "not", 3) && tok_cnt == 2) {
            fputs("(!", out);
            emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], mode, is_header_inline);
            fputc(')', out);
            return;
        }
        if (tok_l[0] == 6 && !strncmp(tok_s[0], "decide", 6) && tok_cnt == 2) {
            fputs("((bool)", out);
            emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], mode, is_header_inline);
            fputc(')', out);
            return;
        }
        if (((tok_l[0] == 4 && !strncmp(tok_s[0], "some", 4)) ||
             (tok_l[0] == 8 && !strncmp(tok_s[0], "interior", 8)) ||
             (tok_l[0] == 5 && !strncmp(tok_s[0], "point", 5))) &&
            tok_cnt == 2) {
            fputc('(', out);
            emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], mode, is_header_inline);
            fputc(')', out);
            return;
        }
        if (tok_l[0] == 8 && !strncmp(tok_s[0], "boundary", 8) && tok_cnt == 2) {
            if (mode == LEAN_EXPR_JET2) {
                fputs("flow_jet2_const(0.0)", out);
            } else {
                fputs(
                    "flowc_make_boundary_tag(0x0FFFU, 0U, (uint8_t)FLOW_BOUNDARY_EXPLICIT_NONE, 62U, (uint16_t)(",
                    out);
                emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], LEAN_EXPR_UINT, is_header_inline);
                fputs("))", out);
            }
            return;
        }
        if (tok_l[0] == 13 && !strncmp(tok_s[0], "flow_quantize", 13) && tok_cnt == 5) {
            fputs("flow_quantize((double)(", out);
            emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], LEAN_EXPR_INT, is_header_inline);
            fputs("), (double)(", out);
            emit_norm_lean_slice(out, ir, tok_s[2], tok_l[2], LEAN_EXPR_INT, is_header_inline);
            fputs("), (double)(", out);
            emit_norm_lean_slice(out, ir, tok_s[3], tok_l[3], LEAN_EXPR_INT, is_header_inline);
            fputs("), (uint32_t)(", out);
            emit_norm_lean_slice(out, ir, tok_s[4], tok_l[4], LEAN_EXPR_UINT, is_header_inline);
            fputs("))", out);
            return;
        }
        if (tok_l[0] == 15 && !strncmp(tok_s[0], "flow_dequantize", 15) && tok_cnt == 5) {
            fputs("flow_dequantize((uint64_t)(", out);
            emit_norm_lean_slice(out, ir, tok_s[1], tok_l[1], LEAN_EXPR_UINT, is_header_inline);
            fputs("), (double)(", out);
            emit_norm_lean_slice(out, ir, tok_s[2], tok_l[2], LEAN_EXPR_INT, is_header_inline);
            fputs("), (double)(", out);
            emit_norm_lean_slice(out, ir, tok_s[3], tok_l[3], LEAN_EXPR_INT, is_header_inline);
            fputs("), (uint32_t)(", out);
            emit_norm_lean_slice(out, ir, tok_s[4], tok_l[4], LEAN_EXPR_UINT, is_header_inline);
            fputs("))", out);
            return;
        }
        if (tok_l[0] > 9 && !strncmp(tok_s[0], "flow_int_", 9)) {
            const char *op_suf = tok_s[0] + 9;
            size_t op_len = tok_l[0] - 9;
            LeanExprMode arg_mode = mode;
            if (op_len == 6 && !strncmp(op_suf, "of_nat", 6))
                arg_mode = LEAN_EXPR_UINT;
            else if (op_len == 6 && !strncmp(op_suf, "of_int", 6))
                arg_mode = LEAN_EXPR_INT;
            if (mode == LEAN_EXPR_JET2)
                fprintf(out, "flow_jet2_%.*s(", (int)op_len, op_suf);
            else
                fprintf(out, "%.*s(", (int)tok_l[0], tok_s[0]);
            for (size_t ti = 1; ti < tok_cnt; ++ti) {
                if (ti > 1)
                    fputs(", ", out);
                emit_norm_lean_slice(out, ir, tok_s[ti], tok_l[ti], arg_mode, is_header_inline);
            }
            fputc(')', out);
            return;
        }
        const FlowLeanFunction *callee = find_ir_lean_fn_len(ir, tok_s[0], tok_l[0]);
        if (mode == LEAN_EXPR_JET2 && callee && is_jet2_eligible_fn(ir, callee)) {
            fprintf(out, "%sjet2_%.*s(", is_header_inline ? "flowc_" : "", (int)tok_l[0], tok_s[0]);
            for (size_t ti = 1; ti < tok_cnt; ++ti) {
                if (ti > 1)
                    fputs(", ", out);
                emit_norm_lean_slice(out, ir, tok_s[ti], tok_l[ti], LEAN_EXPR_JET2,
                                     is_header_inline);
            }
            fputc(')', out);
            return;
        }
        fprintf(out, "%s%.*s(", (callee && is_header_inline) ? "flowc_" : "", (int)tok_l[0],
                tok_s[0]);
        for (size_t ti = 1; ti < tok_cnt; ++ti) {
            if (ti > 1)
                fputs(", ", out);
            emit_norm_lean_slice(out, ir, tok_s[ti], tok_l[ti], mode, is_header_inline);
        }
        fputc(')', out);
        return;
    }
    if ((len == 4 && !strncmp(s, "none", 4)) || (len == 8 && !strncmp(s, "boundary", 8))) {
        if (mode == LEAN_EXPR_JET2)
            fputs("flow_jet2_const(0.0)", out);
        else
            fputs(
                "flowc_make_boundary_tag(0x0FFFU, 0U, (uint8_t)FLOW_BOUNDARY_EXPLICIT_NONE, 62U, 0U)",
                out);
        return;
    }
    if (len > 10 && s[0] == '0' && (s[1] == 'x' || s[1] == 'X') &&
        isxdigit((unsigned char)s[len - 1])) {
        fprintf(out, "%.*sULL", (int)len, s);
        return;
    }
    if (mode == LEAN_EXPR_JET2 && len > 0 && len < 64 && isdigit((unsigned char)s[0])) {
        fprintf(out, "flow_jet2_const(%.*s)", (int)len, s);
        return;
    }
    if (mode == LEAN_EXPR_INT && len > 0 && len < 20 && isdigit((unsigned char)s[0])) {
        int all_dig = 1;
        for (size_t i = 0; i < len; ++i) {
            if (!isdigit((unsigned char)s[i])) {
                all_dig = 0;
                break;
            }
        }
        if (all_dig) {
            fprintf(out, "%.*sLL", (int)len, s);
            return;
        }
    }
    fprintf(out, "%.*s", (int)len, s);
}
static void emit_lean_expr_as_c_ex(FILE *out, const SemanticIR *ir, const char *expr,
                                   LeanExprMode mode, int is_header_inline) {
    char norm[4096];
    flow_lean_normalize_expr(expr, norm, sizeof(norm));
    emit_norm_lean_slice(out, ir, norm, strlen(norm), mode, is_header_inline);
}
