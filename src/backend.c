static int is_lean_kw_at(const char *p, const char *start, const char *end, const char *kw,
                         size_t kwlen) {
    if ((size_t)(end - p) < kwlen || strncmp(p, kw, kwlen) != 0)
        return 0;
    int l_ok = (p == start) || isspace((unsigned char)p[-1]) || p[-1] == '(';
    int r_ok = (p + kwlen == end) || isspace((unsigned char)p[kwlen]) || p[kwlen] == '(' ||
               p[kwlen] == ')';
    return l_ok && r_ok;
}
static void subst_lean_var(const char *src, size_t src_len, const char *var, const char *val,
                           size_t val_len, char *out, size_t out_max) {
    size_t vlen = strlen(var), j = 0;
    for (size_t i = 0; i < src_len && j + 4 < out_max;) {
        if (i + vlen <= src_len && !strncmp(src + i, var, vlen)) {
            int l_ok = (i == 0) || (!isalnum((unsigned char)src[i - 1]) && src[i - 1] != '_');
            int r_ok = (i + vlen == src_len) ||
                       (!isalnum((unsigned char)src[i + vlen]) && src[i + vlen] != '_');
            if (l_ok && r_ok && j + val_len + 3 < out_max) {
                out[j++] = '(';
                memcpy(out + j, val, val_len);
                j += val_len;
                out[j++] = ')';
                i += vlen;
                continue;
            }
        }
        out[j++] = src[i++];
    }
    out[j] = '\0';
}
