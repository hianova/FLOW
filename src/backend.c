static void emit_lean_let_statements_and_tail(FILE *output, const SemanticIR *ir, const char *body,
                                              LeanExprMode mode, int is_header_inline,
                                              const char **tail_out, size_t *tail_len_out) {
    const char *s = body ? body : "";
    size_t len = strlen(s);
    while (len > 0 && isspace((unsigned char)*s)) {
        ++s;
        --len;
    }
    while (len > 0 && isspace((unsigned char)s[len - 1]))
        --len;
    const char *end = s + len;
    const char *ps = NULL, *pe = NULL, *rhs = NULL, *rhs_end = NULL, *rest = NULL;
    while (split_lean_let_slice(s, end, &ps, &pe, &rhs, &rhs_end, &rest)) {
        const char *default_ct = (mode == LEAN_EXPR_JET2)
                                     ? "FlowJetScalar2"
                                     : ((mode == LEAN_EXPR_INT) ? "int64_t" : "uint64_t");
        if (pe - ps >= 2 && ps[0] == '(' && pe[-1] == ')') {
            char tvars[FLOW_TUPLE_MAX][FLOW_NAME] = {{0}};
            size_t tcnt = 0;
            const char *q = ps + 1, *qe = pe - 1;
            while (q < qe && tcnt < FLOW_TUPLE_MAX) {
                while (q < qe && (isspace((unsigned char)*q) || *q == ','))
                    ++q;
                size_t vk = 0;
                while (q < qe && (isalnum((unsigned char)*q) || *q == '_')) {
                    if (vk + 1 < FLOW_NAME)
                        tvars[tcnt][vk++] = *q;
                    ++q;
                }
                while (q < qe && *q != ',')
                    ++q;
                if (tvars[tcnt][0])
                    tcnt++;
            }
            const char *tok_s[FLOW_LEAN_PARAM_MAX + 2];
            size_t tok_l[FLOW_LEAN_PARAM_MAX + 2], tok_cnt = 0;
            for (const char *p = rhs; p < rhs_end && tok_cnt < FLOW_LEAN_PARAM_MAX + 2;) {
                while (p < rhs_end && isspace((unsigned char)*p))
                    ++p;
                if (p >= rhs_end)
                    break;
                const char *ts = p;
                if (*p == '(') {
                    int d = 0;
                    while (p < rhs_end) {
                        if (*p == '(')
                            d++;
                        else if (*p == ')' && --d == 0) {
                            ++p;
                            break;
                        }
                        ++p;
                    }
                } else {
                    while (p < rhs_end && !isspace((unsigned char)*p) && *p != '(' && *p != ')')
                        ++p;
                }
                tok_s[tok_cnt] = ts;
                tok_l[tok_cnt] = (size_t)(p - ts);
                tok_cnt++;
            }
            if (tcnt >= 2 && tok_cnt >= 1) {
                const FlowLeanFunction *callee = find_ir_lean_fn_len(ir, tok_s[0], tok_l[0]);
                for (size_t ti = 0; ti < tcnt; ++ti) {
                    const char *vct = default_ct;
                    if (callee && ti < callee->tuple_arity)
                        vct = lean_type_to_c_type(ir, callee->tuple_types[ti]);
                    fprintf(output, "    %s %s = (%s)0;\n", vct, tvars[ti], vct);
                }
                fprintf(output, "    (void)%s%.*s(", (callee && is_header_inline) ? "flowc_" : "",
                        (int)tok_l[0], tok_s[0]);
                for (size_t ai = 1; ai < tok_cnt; ++ai) {
                    if (ai > 1)
                        fputs(", ", output);
                    emit_norm_lean_slice(output, ir, tok_s[ai], tok_l[ai], mode, is_header_inline);
                }
                for (size_t ti = 0; ti < tcnt; ++ti)
                    fprintf(output, "%s&%s", (tok_cnt > 1 || ti > 0) ? ", " : "", tvars[ti]);
                fputs(");\n", output);
            }
        } else {
            char vname[FLOW_NAME] = {0};
            size_t vk = 0;
            for (const char *p = ps; p < pe && *p != ':' && !isspace((unsigned char)*p); ++p)
                if (vk + 1 < sizeof(vname))
                    vname[vk++] = *p;
            if (vname[0]) {
                if (mode == LEAN_EXPR_JET2) {
                    fprintf(output, "    const %s %s = ", default_ct, vname);
                    emit_norm_lean_slice(output, ir, rhs, (size_t)(rhs_end - rhs), mode,
                                         is_header_inline);
                    fputs(";\n", output);
                } else {
                    fprintf(output, "    const %s %s = (%s)(", default_ct, vname, default_ct);
                    emit_norm_lean_slice(output, ir, rhs, (size_t)(rhs_end - rhs), mode,
                                         is_header_inline);
                    fputs(");\n", output);
                }
            }
        }
        s = rest;
        len = (size_t)(end - rest);
    }
    *tail_out = s;
    *tail_len_out = len;
}
static void split_tuple_tail_slices(const char *s, size_t len, size_t arity, const char **seg_s,
                                    const char **seg_e) {
    while (len >= 2 && s[0] == '(' && s[len - 1] == ')') {
        int d = 0, wrapped = 1;
        for (size_t i = 0; i + 1 < len; ++i) {
            if (s[i] == '(')
                d++;
            else if (s[i] == ')' && --d == 0) {
                wrapped = 0;
                break;
            }
        }
        if (!wrapped)
            break;
        ++s;
        len -= 2;
        while (len > 0 && isspace((unsigned char)*s)) {
            ++s;
            --len;
        }
        while (len > 0 && isspace((unsigned char)s[len - 1]))
            --len;
    }
    const char *end = s + len, *cur = s;
    size_t cnt = 0;
    int pd = 0;
    for (const char *p = s; p < end; ++p) {
        if (*p == '(')
            pd++;
        else if (*p == ')' && pd > 0)
            pd--;
        else if (pd == 0 && *p == ',' && cnt + 1 < arity) {
            seg_s[cnt] = cur;
            seg_e[cnt] = p;
            cnt++;
            cur = p + 1;
        }
    }
    while (cnt < arity) {
        seg_s[cnt] = cur;
        seg_e[cnt] = end;
        cnt++;
    }
}
static void qualify_struct_fields_in_expr(const FlowLeanStruct *st, const char *prefix,
                                          const char *src, char *out, size_t out_max) {
    if (!st || !prefix || !src || !out || out_max == 0)
        return;
    char cur[1024] = {0}, next[1024] = {0};
    snprintf(cur, sizeof(cur), "%s", src);
    for (size_t fi = 0; fi < st->field_count; ++fi) {
        const char *fn = st->fields[fi].name;
        size_t flen = strlen(fn);
        if (flen == 0 || !strchr(fn, '_'))
            continue;
        char dotted[FLOW_NAME] = {0};
        for (const char *u = strchr(fn, '_'); u; u = strchr(u + 1, '_')) {
            if (flen >= sizeof(dotted))
                break;
            memcpy(dotted, fn, flen + 1);
            dotted[u - fn] = '.';
            if (strstr(cur, dotted) != NULL) {
                size_t slen = strlen(cur), j = 0;
                for (size_t i = 0; i < slen && j + flen + 2 < sizeof(next);) {
                    if (i + flen <= slen && !strncmp(cur + i, dotted, flen)) {
                        int l_ok = (i == 0) || (!isalnum((unsigned char)cur[i - 1]) &&
                                                cur[i - 1] != '_' && cur[i - 1] != '.');
                        int r_ok =
                            (i + flen == slen) || (!isalnum((unsigned char)cur[i + flen]) &&
                                                   cur[i + flen] != '_' && cur[i + flen] != '.');
                        if (l_ok && r_ok) {
                            memcpy(next + j, fn, flen);
                            j += flen;
                            i += flen;
                            continue;
                        }
                    }
                    next[j++] = cur[i++];
                }
                next[j] = '\0';
                snprintf(cur, sizeof(cur), "%s", next);
            }
        }
    }
    for (size_t fi = 0; fi < st->field_count; ++fi) {
        const char *fn = st->fields[fi].name;
        size_t flen = strlen(fn);
        if (flen == 0)
            continue;
        char repl[160];
        snprintf(repl, sizeof(repl), "(%s%s)", prefix, fn);
        size_t rlen = strlen(repl), slen = strlen(cur), j = 0;
        for (size_t i = 0; i < slen && j + 4 < sizeof(next);) {
            if (i + flen <= slen && !strncmp(cur + i, fn, flen)) {
                int l_ok = (i == 0) || (!isalnum((unsigned char)cur[i - 1]) && cur[i - 1] != '_' &&
                                        cur[i - 1] != '.');
                int r_ok = (i + flen == slen) || (!isalnum((unsigned char)cur[i + flen]) &&
                                                  cur[i + flen] != '_' && cur[i + flen] != '.');
                if (l_ok && r_ok && j + rlen + 1 < sizeof(next)) {
                    memcpy(next + j, repl, rlen);
                    j += rlen;
                    i += flen;
                    continue;
                }
            }
            next[j++] = cur[i++];
        }
        next[j] = '\0';
        snprintf(cur, sizeof(cur), "%s", next);
    }
    snprintf(out, out_max, "%s", cur);
}
static int is_soa_eligible_fn(const SemanticIR *ir, const FlowLeanFunction *fn) {
    (void)ir;
    return fn && ((fn->variant_mask & FLOW_FN_VAR_SOA64) != 0);
}
static int rewrite_expr_soa_columnar(const SemanticIR *ir, const FlowLeanFunction *fn,
                                     const char *expr, char *out, size_t out_max) {
    if (!ir || !fn || !expr || !out || out_max == 0)
        return 0;
    char cur[FLOW_LEAN_BODY_MAX] = {0}, next[FLOW_LEAN_BODY_MAX] = {0};
    snprintf(cur, sizeof(cur), "%s", expr);
    for (size_t pi = 0; pi < fn->param_count; ++pi) {
        const FlowLeanStruct *in_st = find_ir_lean_struct(ir, fn->param_types[pi]);
        if (!in_st)
            continue;
        const char *pname = fn->param_names[pi];
        for (size_t sfi = 0; sfi < in_st->field_count; ++sfi) {
            const char *fname = in_st->fields[sfi].name;
            char pat[128], repl[160];
            snprintf(pat, sizeof(pat), "%s.%s", pname, fname);
            snprintf(repl, sizeof(repl), "_soa_%s_%s", pname, fname);
            size_t plen = strlen(pat), rlen = strlen(repl), slen = strlen(cur), j = 0;
            for (size_t i = 0; i < slen && j + 4 < sizeof(next);) {
                if (i + plen <= slen && !strncmp(cur + i, pat, plen)) {
                    int l_ok = (i == 0) || (!isalnum((unsigned char)cur[i - 1]) &&
                                            cur[i - 1] != '_' && cur[i - 1] != '.');
                    int r_ok = (i + plen == slen) || (!isalnum((unsigned char)cur[i + plen]) &&
                                                      cur[i + plen] != '_' && cur[i + plen] != '.');
                    if (l_ok && r_ok && j + rlen + 1 < sizeof(next)) {
                        memcpy(next + j, repl, rlen);
                        j += rlen;
                        i += plen;
                        continue;
                    }
                }
                next[j++] = cur[i++];
            }
            next[j] = '\0';
            snprintf(cur, sizeof(cur), "%s", next);
        }
        if (body_has_ident_tok(cur, pname))
            return 0;
    }
    snprintf(out, out_max, "%s", cur);
    return 1;
}

